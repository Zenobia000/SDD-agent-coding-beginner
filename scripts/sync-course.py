def inline(s):
    s = html.escape(s)
    s = re.sub(r'`([^`]+)`', r'<code>\1</code>', s)
    s = re.sub(r'\*\*([^*]+)\*\*', r'<b>\1</b>', s)
    return re.sub(r'\[([^\]]+)\]\(([^)]+)\)', r'<a href="\2">\1</a>', s)

def md(source):
    """Render the limited headings/lists/tables/fences used by these course files."""
    out=[]; lines=source.splitlines(); i=0
    while i<len(lines):
        line=lines[i]; i+=1
        if not line.strip(): continue
        if line.startswith('```'):
            code=[]
            while i<len(lines) and not lines[i].startswith('```'):
                code.append(lines[i]); i+=1
            i+=1; out.append('<pre class="code">'+html.escape('\n'.join(code))+'</pre>'); continue
        if line.startswith('|'):
            rows=[line]
            while i<len(lines) and lines[i].startswith('|'): rows.append(lines[i]);i+=1
            out.append('<div class="tbl-wrap"><table class="tbl">')
            for j,row in enumerate(rows):
                if re.fullmatch(r'[\s|:\-]+',row):continue
                tag='th' if j==0 else 'td'
                out.append('<tr>'+''.join(f'<{tag}>{inline(c.strip())}</{tag}>' for c in row.strip('|').split('|'))+'</tr>')
            out.append('</table></div>');continue
        if re.match(r'^#{1,4} ',line):
            level=min(len(line)-len(line.lstrip('#'))+1,4)
            out.append(f'<h{level}>'+inline(line.lstrip('# '))+f'</h{level}>');continue
        if re.match(r'^[-*] ',line):
            out.append('<ul>')
            while True:
                out.append('<li>'+inline(line[2:])+'</li>')
                if i>=len(lines) or not re.match(r'^[-*] ',lines[i]):break
                line=lines[i];i+=1
            out.append('</ul>');continue
        out.append('<p>'+inline(line.lstrip('> '))+'</p>')
    return '\n'.join(out)

